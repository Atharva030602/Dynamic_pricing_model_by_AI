// Bundles the shared engine into a single ESM file the /api functions import.
import { build } from 'esbuild'
await build({
  entryPoints: ['server/core.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  outfile: 'api/_lib/core.mjs',
  banner: { js: '// GENERATED by scripts/build-api.mjs from src/engine and src/data. Do not edit.' },
})
console.log('api/_lib/core.mjs built')
