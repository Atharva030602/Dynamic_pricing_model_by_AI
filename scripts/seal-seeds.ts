// Generates demo signing keys per creator and seals every seed work.
import { writeFileSync } from 'node:fs'
import { SEED } from '../src/data/works'
import { CREATORS } from '../src/data/seed'
import { fingerprint, generateKeys, sign, verifySeal } from '../src/engine/seal'

const keys: Record<string, Awaited<ReturnType<typeof generateKeys>>> = {}
for (const id of Object.keys(CREATORS)) keys[id] = await generateKeys()
const seals: Record<string, unknown> = {}
for (const w of SEED) {
  const contentHash = await fingerprint(w.body)
  const s = await sign({ workId: w.id, contentHash, creatorId: w.creatorId, signedAt: w.publishedAt, origin: w.disclosure, aiAssistance: w.aiUses, version: 1 }, keys[w.creatorId])
  const v = await verifySeal(s, w.body)
  if (!v.ok) throw new Error('seal failed ' + w.id)
  seals[w.id] = s
}
writeFileSync('src/data/seedSeals.ts', '// Generated by scripts/seal-seeds.ts — demo keys only.\nexport default ' + JSON.stringify({ keys, seals }) + ' as const\n')
console.log('sealed', Object.keys(seals).length)
